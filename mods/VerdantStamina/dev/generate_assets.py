"""Generate our own white annulus masks with antialiased alpha; no game assets."""
from pathlib import Path
import math
import sys

ROOT=Path(__file__).resolve().parents[3]
sys.path.insert(0,str(ROOT/'tools/python'))
from lupa.lua54 import LuaRuntime
from PIL import Image,ImageDraw,PngImagePlugin,ImageStat
from surface_pattern import pattern

def generate():
    lua=LuaRuntime(unpack_returned_tuples=True)
    lua.execute("package.path=... .. '/?.lua;' .. package.path",(ROOT/'mods/VerdantStamina/Scripts').as_posix())
    core=lua.eval("require('core')")[0];config=lua.eval("require('config')")[0]
    core.validate(config)
    rings=core.rings(config.base_capacity+config.bonus_ring_capacity*config.max_bonus_rings,config)
    out=ROOT/'mods/VerdantStamina/Assets';out.mkdir(exist_ok=True)
    for i in range(1,len(rings)+1):
        ring=rings[i];outer=ring.radius+ring.thickness/2;inner=ring.radius-ring.thickness/2
        surfaces={}
        for layer,inset in [('track',0),('fill',min(0.45,ring.thickness*0.16)),
                            ('trackcap',0),('fillcap',min(0.45,ring.thickness*0.16))]:
            n=256
            canvas_radius=outer+1
            pixels=n/(canvas_radius*2)
            ro,ri=outer-inset,inner+inset
            alpha=bytearray(n*n)
            # A one-logical-pixel coverage ramp survives UI downsampling. Merely
            # antialiasing a 256px hard edge becomes subpixel-sharp at HUD size.
            for y in range(n):
                for x in range(n):
                    px,py=(x+0.5-n/2)/pixels,(y+0.5-n/2)/pixels
                    distance=math.hypot(px,py)
                    softness=config.edge_softness
                    coverage=max(0,min(1,(ro-distance)/softness+0.5,(distance-ri)/softness+0.5))
                    if layer.endswith('cap'):
                        # Only the top cut edge is painted. Rotating this image
                        # gives a soft angled end without a hard stencil edge.
                        coverage*=max(0,min(1,0.5-px/softness,(px+5)/softness)) if py<0 else 0
                    alpha[y*n+x]=round(coverage*255)
            mask=Image.frombytes('L',(n,n),bytes(alpha))
            image=Image.new('RGBA',(n,n),(255,255,255,0));image.putalpha(mask)
            meta=PngImagePlugin.PngInfo()
            meta.add_text('Source','Procedural annulus geometry generated by scripts/generate_assets.py')
            meta.add_text('LogicalGeometry',f'outer={outer};inner={inner};inset={inset};canvas_radius={canvas_radius}')
            image.save(out/f'ring-{ring.index}-{layer}.png',pnginfo=meta)
            if layer=='fill':
                for style in ('paint','hatch'):
                    surface=pattern(n,style,pixels)
                    # Fine outside strokes keep a lighter, quieter surface.
                    if ring.index>0:
                        surface=Image.blend(Image.new('L',(n,n),255),surface,.65)
                    mean=round(ImageStat.Stat(surface,mask).mean[0])
                    surfaces[style]=(surface,mean)
                    textured=Image.merge('RGB',(surface,surface,surface)).convert('RGBA')
                    textured.putalpha(mask)
                    textured.save(out/f'ring-{ring.index}-{style}.png',pnginfo=meta)
            elif layer=='fillcap':
                for style,(_,mean) in surfaces.items():
                    # The feathered endpoint uses the body's mean pigment.
                    # Its rotation therefore cannot spin/misalign the grain.
                    cap=Image.new('RGBA',(n,n),(mean,mean,mean,0));cap.putalpha(mask)
                    cap.save(out/f'ring-{ring.index}-{style}cap.png',pnginfo=meta)
    print(f'Generated {len(rings)*8} antialiased surface masks in {out}')

if __name__=='__main__':generate()
